const VIEWED_EXHIBITS = new Set();

export function findDetroitTigersBannerEntry(text) {
  return DETROIT_TIGERS_BANNERS.find(entry => entry.tagline === text) || null;
}

export function trackDetroitTigersBannerView(entryId) {
  VIEWED_EXHIBITS.add(entryId);
  const unlocked = [];
  
  const viewCount = VIEWED_EXHIBITS.size;
  if (viewCount === 5 && !localStorage.getItem('ach_tigers_fan')) {
    localStorage.setItem('ach_tigers_fan', Date.now());
    unlocked.push('tigers_fan');
  }
  if (viewCount === 15 && !localStorage.getItem('ach_tigers_historian')) {
    localStorage.setItem('ach_tigers_historian', Date.now());
    unlocked.push('tigers_historian');
  }
  if (viewCount === 25 && !localStorage.getItem('ach_tigers_master')) {
    localStorage.setItem('ach_tigers_master', Date.now());
    unlocked.push('tigers_master');
  }
  
  // Bobblehead collection achievement
  const bobbleheadIds = ['tigers_bobble_fidrych', 'tigers_bobble_lolich', 'tigers_bobble_tycobb', 'tigers_bobble_hgreenberg', 'tigers_bobble_whorton'];
  const bobbleheadsCollected = bobbleheadIds.filter(id => VIEWED_EXHIBITS.has(id)).length;
  if (bobbleheadsCollected === 5 && !localStorage.getItem('ach_bobblehead_collector')) {
    localStorage.setItem('ach_bobblehead_collector', Date.now());
    unlocked.push('bobblehead_collector');
  }
  
  return unlocked;
}

export function getDetroitTigersBannerViewCount() {
  return VIEWED_EXHIBITS.size;
}