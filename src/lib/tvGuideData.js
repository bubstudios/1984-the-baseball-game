// Pick a random synopsis for a banner
export function pickSynopsis(bannerIndex) {
  const data = TV_SYNOPSES[bannerIndex];
  if (!data) return null;
  const syn = data.synopses[Math.floor(Math.random() * data.synopses.length)];
  return { ...data, synopsis: syn, bannerIndex };
}

