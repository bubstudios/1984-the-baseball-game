// Track VHS/Betamax/LaserDisc views
const VIEWED_EXHIBITS = new Set();

export function findVhsBetamaxLaserDiscEntry(text) {
  return VHS_BETAMAX_LASERDISC_POPUPS.find(entry => entry.tagline === text) || null;
}

export function trackVhsBetamaxLaserDiscView(entryId) {
  VIEWED_EXHIBITS.add(entryId);
  const unlocked = [];
  
  const viewCount = VIEWED_EXHIBITS.size;
  if (viewCount === 5 && !localStorage.getItem('ach_vhs_fan')) {
    localStorage.setItem('ach_vhs_fan', Date.now());
    unlocked.push('vhs_fan');
  }
  if (viewCount === 15 && !localStorage.getItem('ach_format_collector')) {
    localStorage.setItem('ach_format_collector', Date.now());
    unlocked.push('format_collector');
  }
  if (viewCount === 25 && !localStorage.getItem('ach_video_historian')) {
    localStorage.setItem('ach_video_historian', Date.now());
    unlocked.push('video_historian');
  }
  
  return unlocked;
}