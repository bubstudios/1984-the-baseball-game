const COLLECTED_CARDS = new Set();

export function getRandomCard() {
  const randomIndex = Math.floor(Math.random() * TIGERS_ROSTER.length);
  return TIGERS_ROSTER[randomIndex];
}

export function addCollectedCard(cardId) {
  COLLECTED_CARDS.add(cardId);
  const unlocked = [];
  
  const collectedCount = COLLECTED_CARDS.size;
  if (collectedCount === 5 && !localStorage.getItem('ach_card_starter')) {
    localStorage.setItem('ach_card_starter', Date.now());
    unlocked.push('card_starter');
  }
  if (collectedCount === 10 && !localStorage.getItem('ach_card_collector')) {
    localStorage.setItem('ach_card_collector', Date.now());
    unlocked.push('card_collector');
  }
  if (collectedCount === 15 && !localStorage.getItem('ach_card_fanatic')) {
    localStorage.setItem('ach_card_fanatic', Date.now());
    unlocked.push('card_fanatic');
  }
  if (collectedCount === 25 && !localStorage.getItem('ach_complete_roster')) {
    localStorage.setItem('ach_complete_roster', Date.now());
    unlocked.push('complete_roster');
  }
  
  return unlocked;
}

export function getCollectedCards() {
  return Array.from(COLLECTED_CARDS);
}

export function getCollectionProgress() {
  return {
    collected: COLLECTED_CARDS.size,
    total: TIGERS_ROSTER.length,
    percentage: Math.round((COLLECTED_CARDS.size / TIGERS_ROSTER.length) * 100),
  };
}

export function hasCard(cardId) {
  return COLLECTED_CARDS.has(cardId);
}

export function loadCollectionFromStorage() {
  const stored = localStorage.getItem('tigersCardCollection');
  if (stored) {
    const cardIds = JSON.parse(stored);
    cardIds.forEach(id => COLLECTED_CARDS.add(id));
  }
}

export function saveCollectionToStorage() {
  localStorage.setItem('tigersCardCollection', JSON.stringify(Array.from(COLLECTED_CARDS)));
}